By proceeding with this transaction, you acknowledge that you have read, understood, and agree to the following Velocity Suites hotel policies.

1. Check-In Window
The earliest Check-In date of a Booking or Reservation is two (2) days from today (hotel time); any later date is allowed. Check-Out must be at least one (1) day after Check-In.

2. Room Availability Policy
Room types shown during creation reflect availability at the time of your request. Availability is re-verified before your transaction is confirmed, and again immediately before submission is completed, to prevent overbooking.

3. Duplicate/Overlapping Date Prevention
A guest may not hold more than one active Booking or Reservation with overlapping stay dates, regardless of room type. Overlapping requests will be rejected.

4. Check-In and Check-Out Policy
Standard Check-In and Check-Out times apply as posted at the property. Early Check-In or late Check-Out is subject to availability and may incur additional charges.

5. Guest Information and Capacity Policy
The representative guest named on the transaction is responsible for the accuracy of all guest information provided. The declared number of guests must not exceed the selected room's stated capacity.

6. Guest Responsibility Policy
The representative guest is responsible for the conduct of all guests under the transaction and for any damage caused during the stay.

7. Reservation Policy
A Reservation provisionally holds your requested dates and room type pending confirmation and, where applicable, payment verification.

8. Booking Policy
A Booking is confirmed once payment has been submitted and, for GCash payments, verified by hotel staff.

9. Reservation Modification Policy
Reservation details may be modified once prior to conversion or Check-In, subject to room availability for the newly requested dates. A confirmed Booking's room or primary guest can no longer be changed.

10. Reservation-to-Booking Conversion Policy
A Reservation may be converted into a Booking by Velocity Suites once payment requirements are satisfied. Conversion preserves the original stay dates and guest details and does not create a duplicate transaction.

11. Cancellation Policy
A Booking may be cancelled any time before the front desk verifies it; once verified, it can no longer be cancelled. A Reservation may be cancelled until it is verified or converted to a Booking. Any partial payment already made is non-refundable.

12. Non-Refundable Policy
Any amount already paid toward a Booking is non-refundable upon cancellation, except where required by law or expressly approved by hotel management.

13. No-Show Policy
If a guest fails to arrive within the hotel's allowed Check-In window on the scheduled Check-In date, the transaction may be marked as a No-Show and moved to Cancelled status. Amounts already paid remain non-refundable.

14. Payment Verification Policy
GCash payments are reviewed by hotel staff before a transaction is marked Confirmed. Cash payments are settled and verified directly at the property.

15. Partial Payment Policy
Online payment is a partial (down) payment of 20% to 50% of the total amount. The remaining balance is paid at the hotel, at check-in and/or check-out.

16. Hotel's Right to Reject or Cancel
Velocity Suites reserves the right to reject, cancel, or reschedule a Booking or Reservation in cases of suspected fraud, data errors, room unavailability beyond the hotel's control, or violation of these policies.

17. Other Applicable Policies
Additional house rules and applicable local regulations apply throughout the stay and are available at the property.

